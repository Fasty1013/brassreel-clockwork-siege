  /**
   * Registers all Cog Knight animations into the given Phaser Scene.
   */
  public static registerAnimations(scene: Phaser.Scene): void {
    const W = 32;
    const H = 32;

    // 1. Idle
    PixelMatrix.registerAnimationStrip(
      scene,
      'strip_cog_knight_idle',
      'cog_knight_idle',
      this.IDLE_FRAMES,
      MAP,
      W,
      H,
      8,
      -1
    );

    // 2. Move
    PixelMatrix.registerAnimationStrip(
      scene,
      'strip_cog_knight_move',
      'cog_knight_move',
      this.MOVE_FRAMES,
      MAP,
      W,
      H,
      10,
      -1
    );

    // 3. Attack
    PixelMatrix.registerAnimationStrip(
      scene,
      'strip_cog_knight_attack',
      'cog_knight_attack',
      this.ATTACK_FRAMES,
      MAP,
      W,
      H,
      12,
      0
    );

    // 4. Hit
    PixelMatrix.registerAnimationStrip(
      scene,
      'strip_cog_knight_hit',
      'cog_knight_hit',
      this.HIT_FRAMES,
      MAP,
      W,
      H,
      12,
      0
    );

    // 5. Death
    PixelMatrix.registerAnimationStrip(
      scene,
      'strip_cog_knight_death',
      'cog_knight_death',
      this.DEATH_FRAMES,
      MAP,
      W,
      H,
      12,
      0
    );

    // 6. Spawn
    PixelMatrix.registerAnimationStrip(
      scene,
      'strip_cog_knight_spawn',
      'cog_knight_spawn',
      this.SPAWN_FRAMES,
      MAP,
      W,
      H,
      12,
      0
    );

    // Register primary static texture as Frame 0
    PixelMatrix.registerTexture(scene.textures, 'tex_cog_knight', this.IDLE_FRAMES[0], MAP, 1);
  }
