  public static registerAnimations(scene: Phaser.Scene): void {
    const tm = scene.textures;
    PixelMatrix.registerTexture(tm, 'tex_spring_archer', this.IDLE_FRAMES[0], MAP, 2);

    PixelMatrix.registerAnimationStrip(
      scene,
      'anim_strip_archer_idle',
      'spring_archer_idle',
      this.IDLE_FRAMES,
      MAP,
      32,
      32,
      8,
      -1
    );

    PixelMatrix.registerAnimationStrip(
      scene,
      'anim_strip_archer_walk',
      'spring_archer_walk',
      this.WALK_FRAMES,
      MAP,
      32,
      32,
      9,
      -1
    );

    PixelMatrix.registerAnimationStrip(
      scene,
      'anim_strip_archer_attack',
      'spring_archer_attack',
      this.ATTACK_FRAMES,
      MAP,
      32,
      32,
      12,
      0
    );

    PixelMatrix.registerAnimationStrip(
      scene,
      'anim_strip_archer_hit',
      'spring_archer_hit',
      this.HIT_FRAMES,
      MAP,
      32,
      32,
      10,
      0
    );
  }
