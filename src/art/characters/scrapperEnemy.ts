  public static registerAnimations(scene: Phaser.Scene): void {
    const tm = scene.textures;
    PixelMatrix.registerTexture(tm, 'tex_en_scrapper', this.IDLE_FRAMES[0], MAP, 2);

    PixelMatrix.registerAnimationStrip(
      scene,
      'anim_strip_scrapper_idle',
      'scrapper_idle',
      this.IDLE_FRAMES,
      MAP,
      32,
      32,
      8,
      -1
    );

    PixelMatrix.registerAnimationStrip(
      scene,
      'anim_strip_scrapper_walk',
      'scrapper_walk',
      this.WALK_FRAMES,
      MAP,
      32,
      32,
      9,
      -1
    );

    PixelMatrix.registerAnimationStrip(
      scene,
      'anim_strip_scrapper_attack',
      'scrapper_attack',
      this.ATTACK_FRAMES,
      MAP,
      32,
      32,
      12,
      0
    );

    PixelMatrix.registerAnimationStrip(
      scene,
      'anim_strip_scrapper_hit',
      'scrapper_hit',
      this.HIT_FRAMES,
      MAP,
      32,
      32,
      10,
      0
    );
  }
